import { mkdir, readFile, writeFile } from "node:fs/promises";
import { isAbsolute, join, relative, resolve } from "node:path";
import { createHash } from "node:crypto";
import { imagePayload } from "./platforms/wechat/media.ts";
import type { Content, ContentInput } from "@turbopush/shared";

const MAX_ARCHIVE_BYTES = 50 * 1024 * 1024;
const ASSET_REFERENCE = /^asset:([a-f0-9]{64})$/;
export interface PortableAsset {
  hash: string;
  mimeType: "image/png" | "image/jpeg";
  data: string;
}

// Store immutable copies; never move or overwrite the user's originals.
export async function importImages(directory: string, paths: string[]) {
  const destination = resolve(directory, "assets");
  const payloads = [];
  for (const path of paths) payloads.push(await imagePayload(path));
  await mkdir(destination, { recursive: true });
  const imported: string[] = [];
  for (const payload of payloads) {
    const digest = createHash("sha256").update(payload.buffer).digest("hex");
    const target = resolve(
      destination,
      `${digest}.${payload.mimeType === "image/png" ? "png" : "jpg"}`,
    );
    // The filename is currently generated by us, but retain this invariant if
    // naming is changed later. Managed imports must never escape app data.
    const child = relative(destination, target);
    if (!child || child.startsWith("..") || isAbsolute(child))
      throw new Error("托管素材路径无效");
    try {
      await writeFile(target, payload.buffer, { flag: "wx" });
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error;
      if (!(await readFile(target)).equals(payload.buffer))
        throw new Error("托管图片已损坏，请检查素材目录；原文件未修改");
    }
    imported.push(target);
  }
  return imported;
}

export async function exportPortableContents(contents: Content[]) {
  const assets = new Map<string, PortableAsset>();
  let totalBytes = 0;
  const portable: ContentInput[] = [];
  for (const content of contents) {
    if (content.video)
      throw new Error("跨机器归档暂不支持视频素材，请移除视频后重试");
    const rewrite = async (path: string) => {
      const payload = await imagePayload(path);
      const hash = createHash("sha256").update(payload.buffer).digest("hex");
      if (!assets.has(hash)) {
        totalBytes += payload.buffer.length;
        if (assets.size >= 500 || totalBytes > MAX_ARCHIVE_BYTES)
          throw new Error("归档图片最多500个且总大小不能超过50MB");
        assets.set(hash, {
          hash,
          mimeType:
            payload.mimeType === "image/png" ? "image/png" : "image/jpeg",
          data: payload.buffer.toString("base64"),
        });
      }
      return `asset:${hash}`;
    };
    portable.push({
      type: content.type,
      title: content.title,
      body: content.body,
      ...(content.bodyFormat ? { bodyFormat: content.bodyFormat } : {}),
      images: await Promise.all(content.images.map(rewrite)),
      ...(content.cover ? { cover: await rewrite(content.cover) } : {}),
      summary: content.summary,
      author: content.author,
      tags: content.tags,
    });
  }
  return { version: 2 as const, contents: portable, assets: [...assets.values()] };
}

export async function importPortableContents(
  directory: string,
  contents: ContentInput[],
  encodedAssets: PortableAsset[],
) {
  const buffers = new Map<string, { buffer: Buffer; extension: "png" | "jpg" }>();
  let totalBytes = 0;
  for (const asset of encodedAssets) {
    if (buffers.has(asset.hash)) throw new Error(`归档包含重复素材哈希: ${asset.hash}`);
    if (!/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(asset.data))
      throw new Error("归档素材不是规范Base64数据");
    const buffer = Buffer.from(asset.data, "base64");
    if (buffer.length === 0 || buffer.length > 10 * 1024 * 1024)
      throw new Error("归档单张图片必须在10MB以内");
    totalBytes += buffer.length;
    if (totalBytes > MAX_ARCHIVE_BYTES) throw new Error("归档图片总大小不能超过50MB");
    const hash = createHash("sha256").update(buffer).digest("hex");
    if (hash !== asset.hash) throw new Error("归档素材哈希校验失败，文件可能已篡改");
    const png = buffer.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]));
    const jpeg = buffer[0] === 255 && buffer[1] === 216 && buffer[2] === 255;
    if ((asset.mimeType === "image/png" && !png) || (asset.mimeType === "image/jpeg" && !jpeg))
      throw new Error("归档素材MIME与文件内容不一致");
    buffers.set(hash, { buffer, extension: png ? "png" : "jpg" });
  }

  const referenced = new Set<string>();
  const parsedContents = contents.map((content) => {
    if (content.video) throw new Error("跨机器归档不接受视频路径");
    const rewrite = (reference: string) => {
      const match = ASSET_REFERENCE.exec(reference);
      if (!match || !buffers.has(match[1]!)) throw new Error("归档内容引用了缺失或非法的图片素材");
      referenced.add(match[1]!);
      const asset = buffers.get(match[1]!)!;
      return resolve(directory, "assets", `${match[1]}.${asset.extension}`);
    };
    return {
      ...content,
      images: content.images.map(rewrite),
      ...(content.cover ? { cover: rewrite(content.cover) } : {}),
    };
  });
  if (referenced.size !== buffers.size) throw new Error("归档包含未被内容引用的素材");

  const destination = resolve(directory, "assets");
  await mkdir(destination, { recursive: true });
  for (const [hash, asset] of buffers) {
    const target = resolve(destination, `${hash}.${asset.extension}`);
    try {
      await writeFile(target, asset.buffer, { flag: "wx" });
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error;
      if (!(await readFile(target)).equals(asset.buffer))
        throw new Error("本机托管图片已损坏，未导入内容");
    }
  }
  return parsedContents;
}
